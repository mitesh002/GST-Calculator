void main() async {
  WidgetsFlutterBinding.ensureInitialized();
  final prefs = await SharedPreferences.getInstance();
  final billingService = BillingService(prefs);

  runApp(
    Provider<BillingService>.value(
      value: billingService,
      child: const MyApp(),
    ),
  );
}

